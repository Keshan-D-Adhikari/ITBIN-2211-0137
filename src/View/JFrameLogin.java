    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        if (!jTextFieldUserName.getText().trim().isEmpty()) {
            if (!jPasswordField.getPassword().toString().isEmpty()) {
                try {
                    boolean isLogin = new UserController().userLogin(jTextFieldUserName.getText(), jPasswordField.getText());
                    if (isLogin) {
                        new JFrameHome().setVisible(true);
                         JFrameLogin.this.hide();
                    } else {
                        CommonUtils.validationErrorMessage(this, "Please enter valid userName or password");
                        
                    }
                    
                } catch (SQLException ex) {
                    ex.printStackTrace();
                }
            } else {
                CommonUtils.validationErrorMessage(this, "Please enter valid userName or password");
            }
        } else {
            CommonUtils.validationErrorMessage(this, "Please enter valid userName or password");
        }
    }//GEN-LAST:event_jButton2ActionPerformed

