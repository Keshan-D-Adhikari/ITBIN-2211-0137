    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // TODO add your handling code here:

        BarrowerModel barrower = new BarrowerModel();

        if (!jTextFieldMemberId.getText().trim().isEmpty()) {
            if (jDateChooserDueDate.getDate() != null) {
                if (jDateChooserReturnDate.getDate() != null) {

                    barrower.setMemberId(jTextFieldMemberId.getText());
                    barrower.setDueDate(CommonUtils.getStringDate(jDateChooserDueDate.getDate()));
                    barrower.setReturnDate(CommonUtils.getStringDate(jDateChooserReturnDate.getDate()));
                    barrower.setStatus("0");

                    BorrowBooksModel[] borrowBooks = new BorrowBooksModel[2];

                        final String bookId1 = (String) tableModel.getValueAt(0, 0);
                        final String bookName1 = (String) tableModel.getValueAt(0, 1);
                        
                         final String bookId2 = (String) tableModel.getValueAt(1, 0);
                        final String bookName2 = (String) tableModel.getValueAt(1, 1);

                        BorrowBooksModel borrowBooksModel1 = new BorrowBooksModel();
                        borrowBooksModel1.setBookId(bookId1);
                        borrowBooksModel1.setName(bookName1);
                        
                         BorrowBooksModel borrowBooksModel2 = new BorrowBooksModel();
                        borrowBooksModel2.setBookId(bookId2);
                        borrowBooksModel2.setName(bookName2); 
                        
                        
                        borrowBooks[0] = borrowBooksModel1;
                        borrowBooks[1] = borrowBooksModel2;

                    try {
                        int isSaved = borrowerController.saveBarrowData(barrower, borrowBooks);
                        commonUtils.DatabaseFunctionalityMessages(this, isSaved);
                      
                    } catch (SQLException ex) {
                        ex.printStackTrace();
                    }

                } else {
                    //JOPTION PANE jDateChooserReturnDate
                    commonUtils.validationErrorMessage(this, "Please Select Valid Return Date");
                }
            } else {
                //JOPTION PANE jDateChooserDueDate
                commonUtils.validationErrorMessage(this, "Please Select Valid Due Date");
            }

        } else {
            //JOPTION PANE jTextFieldMemberId
            commonUtils.validationErrorMessage(this, "Please enter Valid Member");
        }


    }//GEN-LAST:event_jButton4ActionPerformed

