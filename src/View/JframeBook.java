    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed

        if (jTextFieldBookName.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "PLease enter valid Name", "Error", JOptionPane.ERROR_MESSAGE);
        } else if (jTextFieldPrice.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "PLease enter valid Price", "Error", JOptionPane.ERROR_MESSAGE);
        } else if (jComboBoxLanguage.getSelectedItem().toString().equals("--")) {
            JOptionPane.showMessageDialog(this, "PLease select valid Name", "Error", JOptionPane.ERROR_MESSAGE);
        } else if (jComboBoxCategory.getSelectedItem().toString().equals("--")) {
            JOptionPane.showMessageDialog(this, "PLease select valid Category", "Error", JOptionPane.ERROR_MESSAGE);
        } else if (jTextFieldAuthor.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "PLease enter valid Author", "Error", JOptionPane.ERROR_MESSAGE);
        } else {
            try {
                BookModel Book = new BookModel();
                //  Book.set
                Book.setname(jTextFieldBookName.getText());
                Book.setbookId(jTextFieldBookId.getText());
                Book.setprice(Double.parseDouble(jTextFieldPrice.getText()));
                Book.setlanguage(jComboBoxLanguage.getSelectedItem().toString());
                Book.setcategory(jComboBoxCategory.getSelectedItem().toString());
                Book.setauthor(jTextFieldAuthor.getText());

                int ret = 0;

                if (jTextFieldBookId.isEditable()) {
                    ret = bookController.saveBook(Book);
                }

                if (ret == 1) {
                    JOptionPane.showMessageDialog(this, "Data saved succesfuly!", "Success", JOptionPane.INFORMATION_MESSAGE);
                    CommonUtils.resetComponents(new JComponent[]{jTextFieldBookName, jTextFieldBookId, jTextFieldPrice, jComboBoxLanguage, jComboBoxCategory, jTextFieldAuthor});
                    jTextFieldBookId.setEditable(true);
                } else {
                    JOptionPane.showMessageDialog(this, "Data saved fsiled!", "Error", JOptionPane.ERROR_MESSAGE);
                }
                initBookData();
            } catch (SQLException ex) {
                Logger.getLogger(JframeBook.class.getName()).log(Level.SEVERE, null, ex);
            }
        }

    }//GEN-LAST:event_jButton3ActionPerformed

