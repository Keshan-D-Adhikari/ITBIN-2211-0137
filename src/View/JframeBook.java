public void initBookData() {
        try {

            ResultSet rs = bookController.getAllBooks();
            while (rs.next()) {
                String book_id = rs.getString("book_id");
                String name = rs.getString("name");
                String price = rs.getString("price");
                String language = rs.getString("language");
                String category = rs.getString("category");
                String author = rs.getString("author");

                String[] data = {book_id, name, price, language, category, author};

                tableModel.addRow(data);

            }

            jTableBooks.setModel(tableModel);

            jTableBooks.addMouseListener(new MouseAdapter() {
                @Override
                public void mousePressed(MouseEvent e) {
                    int row = jTableBooks.rowAtPoint(e.getPoint());
                    // Check if a row is selected
                    if (row >= 0 && row < jTableBooks.getRowCount()) {
                        jTableBooks.setRowSelectionInterval(row, row);
                        // Show the popup menu
                        String SelectedBookId = (String) tableModel.getValueAt(jTableBooks.getSelectedRow(), 0);
                        try {
                            ResultSet book = bookController.getBookByID(SelectedBookId);
                            while (book.next()) {
                                jTextFieldBookName.setText(book.getString(2));

                                jTextFieldBookId.setText(book.getString(1));
                                jTextFieldBookId.setEditable(false);

                                jTextFieldPrice.setText(book.getString(3));
                                jComboBoxLanguage.setSelectedItem(book.getString(4));
                                jComboBoxCategory.setSelectedItem(book.getString(5));
                                jTextFieldAuthor.setText(book.getString(6));
                            }
                        } catch (SQLException ex) {
                            ex.printStackTrace();
                        }
                    }
                }

            });

        } catch (Exception ex) {
            ex.printStackTrace();
        }

    }

